"""Pack the three registered substrate scans for the offline demo (requires ffmpeg)."""
import base64
import json
import statistics
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "assets" / "substrate"
SIZE = 1024
SOURCES = {"soil": "opara_plot0_soil", "redSand": "rocknest_58", "gravel": "ganges_river_pebbles"}


def ffmpeg(args, data=None):
    return subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", *args],
                          input=data, stdout=subprocess.PIPE, check=True).stdout


def pixels(asset, channel, size=SIZE):
    return ffmpeg(["-i", str(ROOT / "source" / f"{asset}-{channel}.jpg"), "-vf",
                   f"scale={size}:{size}:flags=area", "-pix_fmt", "rgb24", "-f", "rawvideo", "pipe:1"])


def encoded(pixels):
    jpg = ffmpeg(["-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{SIZE}x{SIZE}", "-i", "pipe:0",
                  "-frames:v", "1", "-pix_fmt", "yuvj444p", "-q:v", "3", "-f", "mjpeg", "pipe:1"], pixels)
    return base64.b64encode(jpg).decode("ascii")


def calibrated_height(asset):
    """Infer height / tile width from the scan's normal slopes, on both tangent axes."""
    calibration = ROOT / "source" / f"{asset}-calibration.json"
    if calibration.is_file():
        return json.loads(calibration.read_text())["heightRatio"]
    size = 256
    height = pixels(asset, "height", size)[::3]
    normals = pixels(asset, "normal", size)
    ratios = []
    for y in range(1, size - 1):
        for x in range(1, size - 1):
            i = y * size + x
            nz = normals[3*i+2] - 127.5
            if nz < 64:
                continue
            slopes = ((height[i-1] - height[i+1], normals[3*i] - 127.5),
                      (height[i+size] - height[i-size], normals[3*i+1] - 127.5))
            for dh, n in slopes:
                if abs(dh) >= 4 and abs(n) >= 8 and n*dh > 0:
                    ratios.append((n/nz) / (dh*size/510))
    return round(statistics.median(ratios), 6)


def bake(asset):
    color = pixels(asset, "color")
    normal = pixels(asset, "normal")
    height = pixels(asset, "height")[::3]
    roughness = pixels(asset, "roughness")[::3]
    # Three.js reads green for roughness. Store height in red of the same registered map.
    surface = bytearray(SIZE*SIZE*3)
    surface[::3] = surface[2::3] = height
    surface[1::3] = roughness
    return {"color": encoded(color), "normal": encoded(normal), "roughness": encoded(surface),
            "heightRatio": calibrated_height(asset)}


if __name__ == "__main__":
    result = {kind: bake(asset) for kind, asset in SOURCES.items()}
    (ROOT / "substrate-scans.js").write_text("// Generated by tools/build_substrate_textures.py\n"
        + "window.AQUARIUM_SUBSTRATE_SCANS = " + json.dumps(result, separators=(",", ":")) + ";\n")
    for kind, data in result.items():
        print(kind, "height / tile width", data["heightRatio"])
