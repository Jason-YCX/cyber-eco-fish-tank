"""Pack the registered Ganges crop. Optional --masters contains original Poly Haven JPEGs."""
import argparse
import base64
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1] / "assets/substrate"
SOURCE = ROOT / "source" / "河砾高清局部"
CHANNELS = {"color": "ganges-diff-16k.jpg", "height": "ganges-disp-8k.jpg",
            "normal": "ganges-nor-8k.jpg", "roughness": "ganges-rough-8k.jpg"}


def registered(image, registration):
    size = registration["size"]
    cell = image.width // (size - 1)
    source_scale = cell / registration["stepIn16kPixels"]
    offsets = {i: (x * source_scale, y * source_scale) for i, x, y in registration["nodes"]}

    def sample(x, y):
        dx, dy = offsets.get(y * size + x, (0, 0))
        return (x * cell + dx, y * cell + dy)

    mesh = []
    for y in range(size - 1):
        for x in range(size - 1):
            box = (x * cell, y * cell, (x + 1) * cell, (y + 1) * cell)
            quad = sample(x, y) + sample(x, y + 1) + sample(x + 1, y + 1) + sample(x + 1, y)
            mesh.append((box, quad))
    return image.transform(image.size, Image.Transform.MESH, mesh, Image.Resampling.BICUBIC)


def build(masters=None):
    if masters:
        Image.MAX_IMAGE_PIXELS = None
        SOURCE.mkdir(exist_ok=True)
        for channel, filename in CHANNELS.items():
            with Image.open(masters / filename) as image:
                width, height = image.size
                crop = image.crop((width // 4, 3 * height // 8, 3 * width // 8, height // 2))
                crop.save(SOURCE / (channel + ".png"), optimize=True)
    from io import BytesIO
    encoded = {}
    registration = json.loads((SOURCE / "registration.json").read_text())
    calibration = json.loads((ROOT / "source/ganges_river_pebbles-calibration.json").read_text())
    encoded["macroHeightRatio"] = calibration["registeredMacroHeightRatio"]
    with Image.open(SOURCE / "height.png") as height, Image.open(SOURCE / "roughness.png") as rough:
        h = height.convert("L")
        surface = Image.merge("RGB", (h, rough.convert("L"), h))
    for name, image in (("color", Image.open(SOURCE / "color.png")),
                        ("normal", Image.open(SOURCE / "normal.png")), ("surface", surface)):
        with image:
            buffer = BytesIO()
            registered(image.convert("RGB"), registration).save(
                buffer, format="JPEG", quality=94, subsampling=0, optimize=True)
            encoded[name] = base64.b64encode(buffer.getvalue()).decode("ascii")
    (ROOT / "river-detail.js").write_text("// Generated by tools/build_river_detail.py\nwindow.AQUARIUM_RIVER_DETAIL="
                                         + json.dumps(encoded, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--masters", type=Path)
    build(parser.parse_args().masters)
