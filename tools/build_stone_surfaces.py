"""Rebuild the offline texture bundle from the CC0 source JPEGs. Requires ffmpeg."""
import base64
import json
from pathlib import Path
import subprocess

from stone_weathering import build_relief

ROOT = Path(__file__).resolve().parents[1]
STONE = ROOT / "assets" / "stone"
SOURCES = STONE / "source-textures"
SCANS = {"dragon": "worn_rock_natural_01", "slate": "cliff_side", "river": "rock_01"}
SIZE = 1024


def ffmpeg(*args, data=None):
    return subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", *args],
        input=data, stdout=subprocess.PIPE, check=True,
    ).stdout


def rgb(path, size=SIZE):
    return ffmpeg("-i", str(path), "-vf", f"scale={size}:{size}:flags=lanczos,vflip",
                  "-pix_fmt", "rgb24", "-f", "rawvideo", "-")


def jpeg(data):
    encoded = ffmpeg("-f", "rawvideo", "-pixel_format", "rgb24", "-video_size", f"{SIZE}x{SIZE}",
                     "-i", "-", "-frames:v", "1", "-pix_fmt", "yuvj444p", "-q:v", "3",
                     "-f", "image2pipe", "-c:v", "mjpeg", "-", data=data)
    return base64.b64encode(encoded).decode("ascii")


def pack(scan):
    albedo = bytearray(rgb(SOURCES / f"{scan}-Diffuse.jpg"))
    normal = bytearray(rgb(SOURCES / f"{scan}-nor_gl.jpg"))
    arm = rgb(SOURCES / f"{scan}-arm.jpg")
    # Mild source AO modulates porous areas; shadows from the modeled cavities remain dynamic.
    for i in range(0, len(albedo), 3):
        shade = .86 + .14 * arm[i] / 255
        albedo[i:i + 3] = bytes(round(c * shade) for c in albedo[i:i + 3])
    normal[2::3] = arm[1::3]  # GL normal X/Y and source roughness in RGB
    return {"color": jpeg(albedo), "surface": jpeg(normal)}


if __name__ == "__main__":
    book = {kind: {**pack(asset), "weathering": build_relief(kind, ffmpeg, rgb(SOURCES / f"{asset}-nor_gl.jpg", 384))}
            for kind, asset in SCANS.items()}
    out = "// Generated by tools/build_stone_surfaces.py from Poly Haven CC0 photographs.\n"
    out += "window.AQUARIUM_ROCK_SURFACES = Object.freeze(" + json.dumps(book, separators=(",", ":")) + ");\n"
    (STONE / "rock-surfaces.js").write_text(out, encoding="utf-8")
